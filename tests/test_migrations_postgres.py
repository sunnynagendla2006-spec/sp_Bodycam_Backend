# 9. Existing evidence survives an upgrade
# ---------------------------------------------------------------------------
@pytest.mark.skipif(not _PG_AVAILABLE, reason=_SKIP_REASON)
def test_existing_evidence_survives_upgrade(disposable_database):
    """
    Brings a database to an OLDER revision (before the two schema-drift
    corrective migrations), inserts a real Incident + Evidence row using
    only the columns that exist at that revision, then upgrades the rest
    of the way to head, and confirms that row is completely unchanged.
    """
    older_head = "6c1a9f3e7b52"  # last revision before the display_id/comment fixes
    older_result = _run_alembic(["upgrade", older_head], disposable_database)
    assert older_result.returncode == 0

    engine = create_engine(disposable_database)
    incident_id = str(uuid_module.uuid4())
    evidence_id = str(uuid_module.uuid4())
    try:
        with engine.begin() as conn:
            conn.execute(text(
                "INSERT INTO incidents (id, location, status) VALUES "
                "(:id, ST_GeomFromEWKT('POINT(5 5)'), 'new')"
            ), {"id": incident_id})
            conn.execute(text(
                "INSERT INTO evidence (id, incident_id, type, upload_status, file_hash) VALUES "
                "(:eid, :iid, 'photo', 'uploaded', :hash)"
            ), {"eid": evidence_id, "iid": incident_id, "hash": "pre-upgrade-hash-12345"})
    finally:
        engine.dispose()

    final_result = _run_alembic(["upgrade", "head"], disposable_database)
    assert final_result.returncode == 0

    verify_engine = create_engine(disposable_database)
    try:
        with verify_engine.connect() as conn:
            row = conn.execute(text(
                "SELECT file_hash, upload_status, incident_id FROM evidence WHERE id = :eid"
            ), {"eid": evidence_id}).fetchone()
        assert row is not None, "Evidence row disappeared after upgrade"
        assert row[0] == "pre-upgrade-hash-12345"
        assert row[1] == "uploaded"
        assert str(row[2]) == incident_id
    finally:
        verify_engine.dispose()


