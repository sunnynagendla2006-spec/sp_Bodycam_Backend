# 10. Downgrade/upgrade cycle on a disposable database
# ---------------------------------------------------------------------------
@pytest.mark.skipif(not _PG_AVAILABLE, reason=_SKIP_REASON)
def test_downgrade_base_then_upgrade_head_cycle(disposable_database):
    up1 = _run_alembic(["upgrade", "head"], disposable_database)
    assert up1.returncode == 0

    down = _run_alembic(["downgrade", "base"], disposable_database)
    assert down.returncode == 0, f"downgrade base failed:\nSTDOUT:\n{down.stdout}\nSTDERR:\n{down.stderr}"

    engine = create_engine(disposable_database)
    try:
        table_names = set(inspect(engine).get_table_names())
        with engine.connect() as conn:
            enum_rows = conn.execute(text(
                "SELECT typname FROM pg_type WHERE typname IN "
                "('userrole','userstatus','constablestatus','incidentstatus','mediatype','uploadstatus','assignmentstatus')"
            )).fetchall()
    finally:
        engine.dispose()

    # Only alembic_version + PostGIS's own spatial_ref_sys should remain --
    # no application tables, and (critically) no orphaned enum types either
    # (see the phase report on why this bug specifically blocked re-upgrade).
    assert not (_APP_TABLE_NAMES & table_names), f"Application tables survived downgrade base: {_APP_TABLE_NAMES & table_names}"
    assert enum_rows == [], f"Orphaned enum types survived downgrade base: {enum_rows}"

    up2 = _run_alembic(["upgrade", "head"], disposable_database)
    assert up2.returncode == 0, f"re-upgrade after downgrade base failed:\nSTDOUT:\n{up2.stdout}\nSTDERR:\n{up2.stderr}"

    final_current = _run_alembic(["current"], disposable_database)
    assert "6b1f4a9d3e72" in final_current.stdout or "6b1f4a9d3e72" in final_current.stderr


# ---------------------------------------------------------------------------
# Extra: importing migration modules must not create database objects as a
# side effect (static check -- does NOT require a live database, so it runs
# unconditionally, unlike the tests above).
# ---------------------------------------------------------------------------
def test_migration_modules_have_no_top_level_op_calls():
    """
    Confirms, via AST inspection (not by importing and hoping nothing
    happens), that every `op.<method>(...)` call in every migration file is
    nested inside a `def upgrade()`/`def downgrade()` function body -- never
    at module level -- so merely importing a migration module (as Alembic
    itself does while building the revision graph, and as this very test
    file's collection does) can never execute DDL as a side effect.
    """
    migration_files = glob.glob(os.path.join(_BACKEND_DIR, "alembic", "versions", "*.py"))
    assert migration_files, "No migration files found -- check the glob path"

    for path in migration_files:
        with open(path) as f:
            tree = ast.parse(f.read(), filename=path)

        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                func = node.func
                is_op_call = (
                    isinstance(func, ast.Attribute)
                    and isinstance(func.value, ast.Name)
                    and func.value.id == "op"
                )
                if not is_op_call:
                    continue
                # Walk up from this Call node to confirm it's nested inside
                # a FunctionDef somewhere (not directly at module level).
                # ast doesn't give parent pointers by default, so re-walk
                # each top-level FunctionDef's own subtree and check
                # membership instead.
        # Simpler equivalent check: every op.* call found anywhere in the
        # module must be reachable by walking INTO some top-level FunctionDef
        # -- i.e. it must not appear when walking the module body with
        # FunctionDef subtrees excluded.
        function_bodies = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                for child in ast.walk(node):
                    function_bodies.add(id(child))

        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                func = node.func
                is_op_call = (
                    isinstance(func, ast.Attribute)
                    and isinstance(func.value, ast.Name)
                    and func.value.id == "op"
                )
                if is_op_call:
                    assert id(node) in function_bodies, (
                        f"{os.path.basename(path)} has an op.* call outside any function body "
                        f"(line {node.lineno}) -- this would execute at import time"
                    )
