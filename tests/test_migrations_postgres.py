"""
Real PostgreSQL Alembic migration tests.

Every test in this file that needs a live database creates and drops its
OWN disposable PostgreSQL database (never touching a shared/dev database),
and invokes the REAL `alembic` CLI as a subprocess (not the Python API
in-process) -- this exercises exactly the same code path
(`alembic/env.py` reading `DATABASE_URL` fresh) that a real deployment
would use, rather than relying on any already-imported, possibly-stale
`app.database` module state in this test process.

HOW TO ACTUALLY RUN THESE TESTS:
    1. Start a real Postgres+PostGIS instance, e.g. via the repo's existing
       docker-compose service:
           docker-compose up -d db
    2. Point TEST_DATABASE_URL at it (only used to derive the admin
       connection + disposable database names -- no tables are ever
       created directly in the database this URL names):
           export TEST_DATABASE_URL="postgresql+psycopg://postgres:postgres_password@localhost:5432/postgres"
    3. Run:
           pytest -m postgres_migration tests/test_migrations_postgres.py -v

Without TEST_DATABASE_URL pointing to a reachable PostgreSQL server, every
test in this file SKIPS (not fails, not fakes a pass).
"""
import os
import subprocess
import uuid as uuid_module
import ast
import glob

import pytest
from sqlalchemy import create_engine, text, inspect
from sqlalchemy.engine import make_url

pytestmark = pytest.mark.postgres_migration

_TEST_DATABASE_URL = os.getenv("TEST_DATABASE_URL") or os.getenv("POSTGRES_TEST_DATABASE_URL")
_BACKEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Known PostGIS TIGER-geocoder/topology system table names -- must NEVER
