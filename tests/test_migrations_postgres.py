# 1. Fresh database upgrade
# ---------------------------------------------------------------------------
@pytest.mark.skipif(not _PG_AVAILABLE, reason=_SKIP_REASON)
def test_fresh_database_upgrade_succeeds(disposable_database):
    result = _run_alembic(["upgrade", "head"], disposable_database)
    assert result.returncode == 0, f"alembic upgrade head failed:\nSTDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"

    current = _run_alembic(["current"], disposable_database)
    assert current.returncode == 0
    assert "6b1f4a9d3e72" in current.stdout or "6b1f4a9d3e72" in current.stderr


